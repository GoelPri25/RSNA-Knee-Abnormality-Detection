"""Speed + fidelity A/B of the ConvNeXt-S (E4-CNXS) fast kernel variants on one Kaggle 2 x T4 VM, internet OFF (user
2026-10-22: "make it as fast as possible and check AUC on gold, shouldn't drop in the fastest version"). Builds
cnxs_speed/submission.py = a driver that runs, one after another in child processes, the eval kernels generated by
fast_r7d/make.py (EVAL_N 883 = gold-58 first, then the 825 fold-0 studies):
  torch               plain torch (fast_cnxs_eval)
  torch_cv            + volume built at the 320 centre crop only
  trt_lean_cv         + TensorRT engine, lean runtime (rsna-cnxs-pack kernel output), pack read at t=0
(v1 also: torch_cold, trt_full_cv = import failed, libnvinfer_plugin missing from the pack; order is ORDER below)
and keeps each child's ms/study line and eval_predictions.json (pred_<tag>.json) for the gold-58 / fold-0 checks on the
host (scratchpad gold58.py vs the training pipeline's gold_kd_e4cnxs.json and val_swa_global.json). No submission.
Usage: python3 -I make.py   (after fast_r7d/make.py eval 883 --cnxs [--trt lean|full] [--cropvol])
"""
import base64
import zlib
from pathlib import Path

H = Path(__file__).resolve().parent
KIDS = {"torch": "fast_cnxs_eval", "torch_cv": "fast_cnxs_cv_eval", "trt_lean_cv": "fast_cnxs_trtlean_cv_eval"}
# v2 order: v1 ran TensorRT last and its reads were the slowest (builder waiting for io 2 s cold torch -> 448 s), so
# TensorRT now runs first on the cold VM, and once more at the end to show the order effect
ORDER = (("trt_lean_cv", "trt_lean_cv"), ("torch_cv", "torch_cv"), ("torch", "torch"), ("trt_lean_cv_2", "trt_lean_cv"))
enc = {}
for tag, d in KIDS.items():
    src = (H.parent / d / "submission.py").read_text()
    assert "EVAL_N = 883\n" in src, (d, "regenerate with eval 883")
    src = src.replace("WARM_NBCONVERT = True ", "WARM_NBCONVERT = False")
    enc[tag] = base64.b64encode(zlib.compress(src.encode(), 9)).decode()

driver = r'''"""ConvNeXt-S fast kernel speed + fidelity A/B (generated by cnxs_speed/make.py; see its docstring)."""
import base64, json, os, subprocess, sys, time, zlib
W = "/kaggle/working"
KIDS = %KIDS%
for tag, b in KIDS.items():
    open(f"{W}/k_{tag}.py", "w").write(zlib.decompress(base64.b64decode(b)).decode())
R = {}
for tag, kid in %ORDER%:
    t = time.perf_counter()
    p = subprocess.run([sys.executable, f"{W}/k_{kid}.py"], capture_output=True, text=True)
    line = [l for l in p.stdout.splitlines() if "ms/study" in l]
    R[tag] = {"rc": p.returncode, "wall_s": round(time.perf_counter() - t, 1),
              "line": (line[-1][:1200] if line else (p.stdout[-800:] + p.stderr[-1500:]))}
    if os.path.exists(f"{W}/eval_predictions.json"):
        os.replace(f"{W}/eval_predictions.json", f"{W}/pred_{tag}.json")
    for f in ("submission.csv",):
        if os.path.exists(f"{W}/{f}"):
            os.remove(f"{W}/{f}")
    print(tag, json.dumps(R[tag]), flush=True)
print("RESULT", json.dumps(R), flush=True)
json.dump(R, open(f"{W}/cnxs_speed.json", "w"), indent=1)
'''
(H / "submission.py").write_text(driver.replace("%KIDS%", repr(enc)).replace("%ORDER%", repr(ORDER)))
print("wrote", H / "submission.py", sum(map(len, enc.values())), "child bytes")
