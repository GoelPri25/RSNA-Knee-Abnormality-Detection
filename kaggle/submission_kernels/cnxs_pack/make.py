"""TensorRT pack for the ConvNeXt-S fast kernel (E4-CNXS weights). Builds cnxs_pack/submission.py = a Kaggle T4 kernel with
internet ON that pip-installs tensorrt-cu12 + tensorrt-lean-cu12 11.4.0.106 + onnx, exports the fp16 backbone
(forward_head(forward_features), static 94 x 3 x 320 x 320 -> 94 x 768; LayerNorm mode LN from cnxs_trt) to ONNX and builds
two engines on this T4 (full plan; version-compatible plan for the lean runtime), then writes /kaggle/working/trtpack:
full/ (tensorrt + bindings + libnvinfer + libnvonnxparser: the tensorrt package imports the parser, which broke trt_full
offline in fast_trt_eval v1), lean/ (tensorrt_lean + bindings + libnvinfer_lean), both engines, manifest.json. Attached as a
kernel source to the offline (internet off) fast kernel.
Usage: python3 -I make.py [fp16|ln32]
"""
import sys
from pathlib import Path

H = Path(__file__).resolve().parent
R7D = "--r7d" in sys.argv                     # R7-D weights (rsna-fast-r7d-weights), vc engine only -> r7d_pack/
TAG = sys.argv[sys.argv.index("--tag") + 1] if "--tag" in sys.argv else "r7d"   # another R7-D-arch model: own names
args = [a for i, a in enumerate(sys.argv[1:], 1) if a not in ("--r7d", "--tag") and sys.argv[i - 1] != "--tag"]
assert TAG == "r7d" or R7D, "--tag needs --r7d"
LN = args[0] if args else "ln32"
assert LN in ("fp16", "ln32")
build = (H.parent / "cnxs_trt" / "make.py").read_text()
b0 = build.index('BUILD = r"""') + len('BUILD = r"""')
BUILD = build[b0:build.index('"""', b0)]
# the pack build: no torch timing / random-input checks beyond one fidelity pass, and an optional version-compatible plan
BUILD = BUILD.replace("""c = b.create_builder_config(); c.set_memory_pool_limit(trt.MemoryPoolType.WORKSPACE, 4 << 30); c.builder_optimization_level = 4
""", """c = b.create_builder_config(); c.set_memory_pool_limit(trt.MemoryPoolType.WORKSPACE, 4 << 30); c.builder_optimization_level = 4
if len(sys.argv) > 3 and sys.argv[3] == "vc":    # lean runtime: version-compatible plan, lean runtime shipped apart
    c.set_flag(trt.BuilderFlag.VERSION_COMPATIBLE); c.set_flag(trt.BuilderFlag.EXCLUDE_LEAN_RUNTIME)
""")
assert BUILD.count("EXCLUDE_LEAN_RUNTIME") == 1
BUILD = BUILD.replace('f"/kaggle/working/cnxs_{mode}.onnx"', 'f"/kaggle/working/cnxs_{mode}_{sys.argv[3]}.onnx"')
BUILD = BUILD.replace("eng = trt.Runtime(L).deserialize_cuda_engine(ser)",
                      "rt = trt.Runtime(L); rt.engine_host_code_allowed = True; eng = rt.deserialize_cuda_engine(ser)")

driver = r'''"""TensorRT pack for the ConvNeXt-S fast kernel (generated by cnxs_pack/make.py; see its docstring)."""
import glob, hashlib, json, os, shutil, subprocess, sys, time
P = "/kaggle/working/trtpack"; os.makedirs(P, exist_ok=True); M = {"ln": "%LN%"}
t = time.perf_counter()
p = subprocess.run([sys.executable, "-m", "pip", "install", "-q", "tensorrt-cu12==11.4.0.106", "tensorrt-lean-cu12==11.4.0.106", "onnx"],
                   capture_output=True, text=True)
M["pip_s"] = round(time.perf_counter() - t, 1); print("pip", p.returncode, p.stderr[-1500:], flush=True); assert p.returncode == 0
BUILD = r"""%BUILD%"""
open("/kaggle/working/build.py", "w").write(BUILD)
for tag in ("full", "vc"):
    p = subprocess.run([sys.executable, "/kaggle/working/build.py", f"{P}/cnxs_{tag}.engine", "%LN%", tag], capture_output=True, text=True)
    print(tag, p.returncode, p.stdout[-800:], p.stderr[-2500:], flush=True); assert p.returncode == 0
    M[f"build_{tag}"] = json.loads(p.stdout.strip().splitlines()[-1])
for f in glob.glob("/kaggle/working/*.onnx"):
    os.remove(f)
import site
sp = [d for d in site.getsitepackages() if os.path.isdir(os.path.join(d, "tensorrt_libs"))][0]
def cp(pkg, dst, only=None):
    src = os.path.join(sp, pkg); os.makedirs(os.path.join(P, dst, pkg), exist_ok=True)
    for f in os.listdir(src):
        if f == "__pycache__" or (only and f not in only):
            continue
        s = os.path.join(src, f); d = os.path.join(P, dst, pkg, f)
        (shutil.copytree if os.path.isdir(s) else shutil.copy2)(s, d)
M["tensorrt_libs"] = sorted(os.listdir(os.path.join(sp, "tensorrt_libs")))
cp("tensorrt", "full"); cp("tensorrt_bindings", "full")
cp("tensorrt_libs", "full", {"__init__.py", "libnvinfer.so.11", "libnvonnxparser.so.11"})
cp("tensorrt_lean", "lean"); cp("tensorrt_lean_bindings", "lean"); cp("tensorrt_lean_libs", "lean")
def sha(f):
    h = hashlib.sha256()
    with open(f, "rb") as fh:
        for b in iter(lambda: fh.read(1 << 20), b""): h.update(b)
    return h.hexdigest()
M["files"] = {os.path.relpath(f, P): [os.path.getsize(f), sha(f)] for f in sorted(glob.glob(f"{P}/**/*", recursive=True)) if os.path.isfile(f)}
import torch
M["gpu"] = torch.cuda.get_device_name(0); M["python"] = sys.version.split()[0]; M["torch"] = torch.__version__
M["total_MB"] = round(sum(v[0] for v in M["files"].values()) / 1e6, 1)
json.dump(M, open(f"{P}/manifest.json", "w"), indent=1)
print("PACK", json.dumps({k: v for k, v in M.items() if k != "files"}), flush=True)
'''
out = driver.replace("%LN%", LN).replace("%BUILD%", BUILD)
OUT = H
if R7D:
    out = out.replace("cnxs_global_fp16.pt", "r7d_global_fp16.pt").replace('f"{P}/cnxs_{tag}.engine"', 'f"{P}/r7d_{tag}.engine"')
    out = out.replace('for tag in ("full", "vc"):', 'for tag in ("vc",):')
    out = out.replace('cp("tensorrt", "full"); cp("tensorrt_bindings", "full")\n', "")
    out = out.replace('cp("tensorrt_libs", "full", {"__init__.py", "libnvinfer.so.11", "libnvonnxparser.so.11"})\n', "")
    out = out.replace('cp("tensorrt_lean", "lean"); cp("tensorrt_lean_bindings", "lean"); cp("tensorrt_lean_libs", "lean")\n', "")
    assert "r7d_global_fp16.pt" in out and "cnxs_global_fp16" not in out and 'cp("tensorrt' not in out
    OUT = H.parent / "r7d_pack"
    OUT.mkdir(exist_ok=True)
    import json
    m = json.loads((H / "kernel-metadata.json").read_text())
    m.update(id="tumis001/rsna-r7d-pack", title="rsna-r7d-pack", dataset_sources=["tumis001/rsna-fast-r7d-weights"])
    if TAG != "r7d":
        out = out.replace("r7d", TAG); m = json.loads(json.dumps(m).replace("r7d", TAG))
        OUT = H.parent / f"{TAG}_pack"; OUT.mkdir(exist_ok=True)
    (OUT / "kernel-metadata.json").write_text(json.dumps(m, indent=2))
(OUT / "submission.py").write_text(out)
print("wrote", OUT / "submission.py", "LN", LN)
