"""fast_global/submission.py -> fast_rap2d/submission.py (PUB-KD rap2-D CoAtNet, global head): same io / volume code,
model swapped. Usage: python3 -I make.py [eval EVAL_N] [--autocast] [--record] [--trace pagetrace.json]  (eval: MODE eval + REF = the rap2-D run's
val_swa_global.json; --autocast: HALF = False)."""
import sys
from pathlib import Path

H = Path(__file__).resolve().parent
s = (H.parent / "fast_global/submission.py").read_text()


def sub(a, b, n=1):
    global s
    assert s.count(a) == n, (a, s.count(a))
    s = s.replace(a, b)


sub('''"""Fast global-only submission (efficiency track): r50-GL v4 l4copy global head (F1 / E4-ALL weights), nothing else.
Same model output as the global head of the E4 / F1 kernels; the speed comes from the code path:''',
    '''"""Fast rap2-D submission: PUB-KD rap2-D (Raptor 384 init CoAtNet-rmlp-2, full-blend mix73 targets, SWA 4-6), global
head only, at 384 (no centre crop). The FAST-G kernel (fast_global/submission.py, generated by fast_rap2d/make.py) with
the model swapped; the speed comes from the code path:''')
sub('''  model   plain-torch ResNet-50, BatchNorm folded into fp16 convs (slim weights), no timm''',
    '''  model   timm 1.0.29 imported from a zip of its precompiled cp313 .pyc, copied to local disk at t=0 (no pip, no compile), built directly on each GPU, fp16 weights (backbone
          only; head fp32), HALF: whole backbone in fp16 (else autocast), windows in chunks of WIN_CHUNK, one model per GPU''')
sub('SLIM = "tumis001/rsna-fast-e4all-weights/e4all_global_fp16.pt"',
    'SLIM = "tumis001/rsna-fast-rap2d-weights/rap2d_global_fp16.pt"\n'
    'TIMM = "tumis001/rsna-fast-rap2d-weights/timm_1.0.29_cp313_pyc.pyz"\n'
    f'HALF = {"--autocast" not in sys.argv}\nWIN_CHUNK = 48')
sub('''    wt = threading.Thread(target=fetch, daemon=True)
    wt.start()''', '''    wt = threading.Thread(target=fetch, daemon=True)
    wt.start()

    def fetch_timm():                                        # zipimport makes ~220 small reads: on gcsfuse that is
        import shutil                                         # 15-50 s (fast_rap2d v3), so one sequential copy to local disk
        shutil.copyfile(find(TIMM), "/tmp/timm_cp313.pyz")
    tt = threading.Thread(target=fetch_timm, daemon=True)
    tt.start()''')
sub('''    ctx = [threading.Thread(target=torch.zeros, args=(1,), kwargs={"device": d}, daemon=True) for d in devs]''',
    '''    def cuwarm(d):                                           # CUDA context + cuDNN / cuBLAS handles and libraries
        a = torch.zeros(2, 64, 16, 16, device=d, dtype=torch.half).contiguous(memory_format=torch.channels_last)
        F.conv2d(a, torch.zeros(64, 64, 3, 3, device=d, dtype=torch.half).contiguous(memory_format=torch.channels_last), padding=1)
        torch.zeros(64, 64, device=d, dtype=torch.half) @ torch.zeros(64, 64, device=d, dtype=torch.half)
        torch.cuda.synchronize(d)
    ctx = [threading.Thread(target=cuwarm, args=(d,), daemon=True) for d in devs]''')
sub('IMG, CROP_MM, EVAL_RES, EVAL_WINDOWS = 384, 140.0, 320, 94', 'IMG, CROP_MM, EVAL_RES, EVAL_WINDOWS = 384, 140.0, 384, 94')
sub('LAYERS = (3, 4, 6, 3)\n', '')
sub('''    import torch.nn.functional as F
    stage("torch", stages)''', '''    import torch.nn.functional as F
    stage("torch", stages)
    import sys
    import types
    tt.join()
    tz = "/tmp/timm_cp313.pyz"
    sys.path.insert(0, tz)
    # only CoAtNet's own modules (81 of timm's 220; bit-identical output, 3x faster import): timm / timm.models /
    # timm.data as bare packages (their __init__ imports every architecture and torchvision transforms), and a
    # placeholder torchvision (timm.layers imports FrozenBatchNorm2d for its freeze utilities, unused here)
    for n in ("torchvision", "torchvision.ops", "torchvision.ops.misc"):
        sys.modules[n] = types.ModuleType(n)
    sys.modules["torchvision.ops.misc"].FrozenBatchNorm2d = type("FrozenBatchNorm2d", (torch.nn.Module,), {})
    for n in ("timm", "timm.models", "timm.data"):
        m = types.ModuleType(n)
        m.__path__ = [tz + "/" + n.replace(".", "/")]
        sys.modules[n] = m
    sys.modules["timm"].__version__ = "1.0.29"
    import timm.data.constants as tdc
    vars(sys.modules["timm.data"]).update({k: v for k, v in vars(tdc).items() if k.isupper()})
    from timm.models.maxxvit import coatnet_rmlp_2_rw_384
    stage("timm", stages)''')
sub('''        W = {k: (v.to(dev).contiguous(memory_format=torch.channels_last) if v.dim() == 4 else v.to(dev)) for k, v in W0.items()}
        t_w = time.perf_counter() - T0

        def features(x):
            x = F.max_pool2d(F.relu(F.conv2d(x, W["stem.w"], W["stem.b"], 2, 3)), 3, 2, 1)
            for li, nb in enumerate(LAYERS, 1):
                for bi in range(nb):
                    p, s = f"layer{li}.{bi}", (2 if li > 1 and bi == 0 else 1)
                    h = F.relu(F.conv2d(x, W[p + ".c1.w"], W[p + ".c1.b"]))
                    h = F.relu(F.conv2d(h, W[p + ".c2.w"], W[p + ".c2.b"], s, 1))
                    h = F.conv2d(h, W[p + ".c3.w"], W[p + ".c3.b"])
                    x = F.relu(h + (F.conv2d(x, W[p + ".ds.w"], W[p + ".ds.b"], s) if bi == 0 else x))
            return x
''', '''        W = {k: v.to(dev) for k, v in W0.items() if not k.startswith("backbone.")}
        with torch.device(dev):
            bb = coatnet_rmlp_2_rw_384(pretrained=False, num_classes=0, img_size=IMG)
        bb.load_state_dict({k[9:]: v for k, v in W0.items() if k.startswith("backbone.")}, strict=True)
        bb = (bb.half() if HALF else bb).eval().to(memory_format=torch.channels_last)
        t_w = time.perf_counter() - T0

        def features(x):
            with torch.autocast("cuda", dtype=torch.float16, enabled=not HALF):
                return torch.cat([bb.forward_features(x[i:i + WIN_CHUNK])
                                  for i in range(0, len(x), WIN_CHUNK)])
''')
if "--record" in sys.argv:                              # write pagetrace.json at the end (resident pages of this model's run)
    sub('RECORD = False', 'RECORD = True')
if "--trace" in sys.argv:                               # embed a recorded trace (fast_rap2d/pagetrace.json) instead of FAST-G's
    import base64, json, re, zlib
    tr = json.loads(Path(sys.argv[sys.argv.index("--trace") + 1]).read_text())
    enc = base64.b64encode(zlib.compress(json.dumps(tr, separators=(",", ":")).encode(), 9)).decode()
    s, n = re.subn(r'^PAGETRACE = ".*"$', lambda m: f'PAGETRACE = "{enc}"', s, flags=re.M)
    assert n == 1
if sys.argv[1:2] == ["eval"]:
    sub('MODE = "submit"', 'MODE = "eval"', 2)  # docstring line + assignment
    sub('EVAL_N = 825', f'EVAL_N = {int(sys.argv[2])}')
    sub('REF = None', 'REF = "tumis001/rsna-fast-rap2d-weights/rap2d_val_swa_global.json"')
    out = H.parent / "fast_rap2d_eval/submission.py"
else:
    out = H / "submission.py"
out.parent.mkdir(exist_ok=True)
out.write_text(s)
print("wrote", out)
