"""Offline TensorRT test of the E4-ALL fast kernel (user 2026-10-22: TensorRT gave -18% ms/study with pip-installed
TensorRT; this checks the shippable form). Builds fast_trt_eval/submission.py = a driver that, on Kaggle's 2 x T4 with
internet OFF, runs the fast eval pipeline (fast_global_eval, unchanged except a BACKEND switch in features()) on all 883
studies (FAST-G's set): torch (cold file cache), torch, trt lean, trt full. TensorRT comes only from the rsna-trt-pack
kernel output (trt_pack/: T4-built engines, lean runtime 111 MB / full runtime libnvinfer 670 MB, no pip). Reports
ms/study, total wall and the ready times, and predictions vs the torch run (FAST-G fidelity gate: max |dp| < 0.01,
mean < 0.001).
Usage: python3 -I make.py
"""
import base64
import zlib
from pathlib import Path

H = Path(__file__).resolve().parent
src = (H.parent / "fast_global_eval" / "submission.py").read_text()


def sub(a, b, n=1):
    global src
    assert src.count(a) == n, (a, src.count(a))
    src = src.replace(a, b)


sub("EVAL_N = 883\n", 'EVAL_N = int(os.environ.get("EVAL_N", "883"))\nBACKEND = os.environ.get("BACKEND", "torch")\n'
    'ENGINE = os.environ.get("ENGINE", "")\nTRT_PATH = os.environ.get("TRT_PATH", "")\n')
sub("WARM_NBCONVERT = True ", "WARM_NBCONVERT = False")
sub("""            return x

        def head(fm):""", """            return x
        if BACKEND in ("trt_lean", "trt_full"):               # TensorRT fp16 engine for features(), runtime from the pack
            import sys
            if TRT_PATH not in sys.path:
                sys.path.insert(0, TRT_PATH)
            if BACKEND == "trt_lean":
                import tensorrt_lean as trt
            else:
                import tensorrt as trt
            torch.cuda.set_device(dev)
            eng = trt.Runtime(trt.Logger(trt.Logger.WARNING)).deserialize_cuda_engine(open(ENGINE, "rb").read())
            tctx = eng.create_execution_context()
            fout = torch.empty((EVAL_WINDOWS, 2048, EVAL_RES // 32, EVAL_RES // 32), dtype=torch.half, device=dev)
            tstream = torch.cuda.Stream(dev)                  # TensorRT on its own stream (default stream = extra syncs)

            def features(x):                                  # noqa: F811
                x = x.contiguous()                            # engine input is linear NCHW
                cur = torch.cuda.current_stream(dev); tstream.wait_stream(cur)
                tctx.set_tensor_address("x", x.data_ptr()); tctx.set_tensor_address("f", fout.data_ptr())
                tctx.execute_async_v3(tstream.cuda_stream); cur.wait_stream(tstream)
                return fout

        def head(fm):""")
child = base64.b64encode(zlib.compress(src.encode(), 9)).decode()

driver = r'''"""Offline TensorRT test on the E4-ALL fast kernel (generated by fast_trt_eval/make.py; see its docstring)."""
import base64, glob, json, os, subprocess, sys, time, zlib
W = "/kaggle/working"
CHILD = "%CHILD%"
open(f"{W}/fg_eval.py", "w").write(zlib.decompress(base64.b64decode(CHILD)).decode())
man = glob.glob("/kaggle/input/**/trtpack/manifest.json", recursive=True)[0]; P = os.path.dirname(man)
R = {"pack": {k: v for k, v in json.load(open(man)).items() if k != "files"}}
runs = [("torch_cold", "torch", "", ""), ("torch", "torch", "", ""),
        ("trt_lean", "trt_lean", f"{P}/lean", f"{P}/r50_e4all_vc.engine"),
        ("trt_full", "trt_full", f"{P}/full", f"{P}/r50_e4all_full.engine"),
        ("torch2", "torch", "", "")]
for tag, be, tp, eng in runs:
    t = time.perf_counter()
    p = subprocess.run([sys.executable, f"{W}/fg_eval.py"], capture_output=True, text=True,
                       env={**os.environ, "BACKEND": be, "ENGINE": eng, "TRT_PATH": tp})
    line = [l for l in p.stdout.splitlines() if "ms/study" in l]
    R[tag] = {"rc": p.returncode, "wall_s": round(time.perf_counter() - t, 1),
              "line": (line[-1].split(" | cpus")[0][:600] if line else p.stderr[-1500:])}
    if os.path.exists(f"{W}/eval_predictions.json"):
        os.replace(f"{W}/eval_predictions.json", f"{W}/pred_{tag}.json")
    print(tag, json.dumps(R[tag]), flush=True)
def load(tag):
    j = json.load(open(f"{W}/pred_{tag}.json")); return {r["study_id"]: r["probabilities"] for r in j["predictions"]}
if os.path.exists(f"{W}/pred_torch.json"):
    base = load("torch")
    for tag in ("torch_cold", "trt_lean", "trt_full", "torch2"):
        if os.path.exists(f"{W}/pred_{tag}.json"):
            o = load(tag); d = [abs(a - b) for s in base for a, b in zip(base[s], o[s])]
            R[f"fid_{tag}"] = {"max": round(max(d), 5), "mean": round(sum(d) / len(d), 6), "n": len(base)}
print("RESULT", json.dumps(R), flush=True)
json.dump(R, open(f"{W}/trt_eval.json", "w"), indent=1)
'''
(H / "submission.py").write_text(driver.replace("%CHILD%", child))
print("wrote", H / "submission.py", len(child), "child bytes")
